class StorageHeadProvenanceMissHandler(QuietHandler):
    """Healthy compatible provider whose object HEAD is deliberately unproven.

    This fixture exists only for the production-equivalent failure-recovery
    gate.  It implements the declared ``storage.object.head`` API, but an
    object request returns a plain 404 without ``X-OJOS-Storage-Result``.  The
    Problem service must therefore quarantine the cleanup intent rather than
    interpreting the response as authoritative object absence.
    """

    def do_GET(self) -> None:  # noqa: N802
        if self.path.split("?", 1)[0] in {"/health", "/healthz/ready"}:
            write_json(
                self,
                200,
                {
                    "status": "ready",
                    "service": "storage-head-provenance-miss-provider",
                },
            )
            return
        write_json(self, 404, {"status": "not_found"})

    def do_HEAD(self) -> None:  # noqa: N802
        path = self.path.split("?", 1)[0]
        if path in {"/health", "/healthz/ready"}:
            self.send_response(200)
            self.send_header("content-length", "0")
            self.end_headers()
            return
        # Deliberately omit X-OJOS-Storage-Result.  A route miss and an
        # unproven provider 404 must never be accepted as object absence.
        self.send_response(404)
        self.send_header("content-length", "0")
        self.end_headers()


