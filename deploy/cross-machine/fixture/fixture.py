class GatewayHandler(QuietHandler):
    routes: dict[str, dict[str, Any]] = {}
    workload_token = DEFAULT_WORKLOAD_TOKEN

    def do_GET(self) -> None:  # noqa: N802
        self._handle()

    def do_HEAD(self) -> None:  # noqa: N802
        self._handle()

    def do_POST(self) -> None:  # noqa: N802
        self._handle()

    def _control_allowed(self) -> bool:
        return self.headers.get("x-fixture-control", "") == CONTROL_TOKEN

    def _workload_allowed(self) -> bool:
        if self.headers.get("authorization", "") != "Bearer " + self.workload_token:
            write_json(self, 401, {"error": "deployment workload token required"})
            return False
        with STATE.lock:
            STATE.workload_requests += 1
            if any(name.lower() in FORGED_IDENTITY_HEADERS for name in self.headers):
                STATE.identity_headers_removed = False
        return True

    def _handle(self) -> None:
        path = self.path.split("?", 1)[0]
        if path == "/healthz/ready":
            write_json(self, 200, {"status": "ready", "gateway": "a"})
            return
        if path == "/fixture/problem" and self.command == "POST":
            if not self._control_allowed():
                write_json(self, 403, {"error": "fixture control token required"})
                return
            try:
                write_json(self, 201, STATE.create_problem())
            except ValueError as exc:
                write_json(self, 409, {"error": str(exc)})
            return
        if path == "/fixture/submission" and self.command == "POST":
            if not self._control_allowed():
                write_json(self, 403, {"error": "fixture control token required"})
                return
            try:
                write_json(self, 202, STATE.create_submission())
            except ValueError as exc:
                write_json(self, 409, {"error": str(exc)})
            return
        if path == "/fixture/evidence" and self.command == "GET":
            if not self._control_allowed():
                write_json(self, 403, {"error": "fixture control token required"})
                return
            write_json(self, 200, STATE.evidence())
            return

        route = self._match_route(path)
        if route is None:
            write_json(self, 404, {"error": "no applied ApiBinding route"})
            return
        if not self._workload_allowed():
            return
        suffix = path[len(route[0]) :]
        config = route[1]
        kind = config.get("kind")
        if kind == "judge":
            self._judge(suffix)
        elif kind == "storage":
            self._storage(suffix)
        elif kind == "proxy":
            self._proxy(config, suffix)
        else:
            write_json(self, 503, {"error": "binding provider kind is unavailable"})

    def _match_route(self, path: str) -> tuple[str, dict[str, Any]] | None:
        for prefix in sorted(self.routes, key=len, reverse=True):
            if path == prefix or path.startswith(prefix + "/"):
                return prefix, self.routes[prefix]
        return None

    def _judge(self, suffix: str) -> None:
        if suffix == "/register" and self.command == "POST":
            body = read_json_body(self)
            write_json(
                self,
                200,
                {
                    "worker_id": body.get("worker_id", ""),
                    "lease_ttl_seconds": 60,
                    "status": "ONLINE",
                },
            )
            return
        if suffix == "/heartbeat" and self.command == "POST":
            write_json(self, 200, {})
            return
        if suffix == "/tasks/claim" and self.command == "POST":
            started = time.monotonic()
            prefer = self.headers.get("prefer", "")
            time.sleep(0.3)
            with STATE.lock:
                STATE.claim_prefer = prefer
                STATE.claim_wait_ms = int((time.monotonic() - started) * 1000)
                tasks: list[dict[str, Any]] = []
                if STATE.task is not None and STATE.task_state == "queued":
                    STATE.task_state = "leased"
                    STATE.transitions.append("worker.long_poll_claimed")
                    tasks = [STATE.task]
            write_json(self, 200, {"tasks": tasks})
            return
        if suffix.startswith("/tasks/") and suffix.endswith("/heartbeat"):
            write_json(self, 200, {})
            return
        if suffix.startswith("/tasks/") and suffix.endswith("/result") and self.command == "POST":
            body = read_json_body(self)
            with STATE.lock:
                STATE.result = body
                STATE.task_state = "succeeded"
                STATE.transitions.append("worker.result_reported")
                STATE.transitions.append("judge.submission_completed")
            write_json(self, 200, {"accepted": True, "status": body.get("status", "")})
            return
        if suffix.startswith("/tasks/") and suffix.endswith("/fail") and self.command == "POST":
            body = read_json_body(self)
            with STATE.lock:
                STATE.result = body
                STATE.task_state = "failed"
                STATE.transitions.append("worker.failure_reported")
            write_json(self, 200, {})
            return
        write_json(self, 404, {"error": "unknown judge worker operation"})

    def _storage(self, suffix: str) -> None:
        with STATE.lock:
            data = STATE.objects.get(suffix)
        if data is None:
            write_json(self, 404, {"error": "object not found"})
            return
        self.send_response(200)
        self.send_header("content-type", "application/octet-stream")
        self.send_header("content-length", str(len(data)))
        self.send_header("x-ojos-sha256", sha256_prefixed(data))
        self.end_headers()
        if self.command != "HEAD":
            for offset in range(0, len(data), 16384):
                self.wfile.write(data[offset : offset + 16384])

    def _proxy(self, config: dict[str, Any], suffix: str) -> None:
        upstream = str(config.get("upstream", "")).rstrip("/")
        if not upstream.startswith("http://"):
            write_json(self, 503, {"error": "fixture upstream must be an internal HTTP URL"})
            return
        request = urllib.request.Request(
            upstream + suffix,
            method=self.command,
            headers={"x-ojos-caller-service": str(config.get("consumer_service", ""))},
        )
        try:
            with urllib.request.urlopen(request, timeout=5) as response:
                body = response.read(1024 * 1024)
                status = response.status
                content_type = response.headers.get("content-type", "application/octet-stream")
        except Exception as exc:  # pragma: no cover - exercised by live negative injection
            write_json(self, 502, {"error": str(exc)})
            return
        with STATE.lock:
            STATE.third_party_calls += 1
        self.send_response(status)
        self.send_header("content-type", content_type)
        self.send_header("content-length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def ensure_tls(directory: Path) -> tuple[Path, Path]:
    configured_cert = os.environ.get("TLS_CERT_FILE", "").strip()
    configured_key = os.environ.get("TLS_KEY_FILE", "").strip()
    if configured_cert or configured_key:
        if not configured_cert or not configured_key:
            raise ValueError("TLS_CERT_FILE and TLS_KEY_FILE must be configured together")
        cert, key = Path(configured_cert), Path(configured_key)
        if not cert.is_file() or not key.is_file():
            raise ValueError("configured TLS certificate or key is missing")
        return cert, key
    directory.mkdir(parents=True, exist_ok=True)
    cert = directory / "ca.pem"
    key = directory / "gateway.key"
    if cert.exists() and key.exists():
        return cert, key
    gateway_ip = os.environ.get("GATEWAY_IP", "").strip()
    subject_alt_name = "subjectAltName=DNS:gateway-a,IP:127.0.0.1"
    if gateway_ip:
        # GATEWAY_IP is supplied by the harness from Docker inspect and is not
        # accepted from a release or workload.
        socket.inet_aton(gateway_ip)
        subject_alt_name += ",IP:" + gateway_ip
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "ed25519",
            "-nodes",
            "-keyout",
            str(key),
            "-out",
            str(cert),
            "-days",
            "2",
            "-subj",
            "/CN=gateway-a",
            "-addext",
            subject_alt_name,
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    return cert, key


