class TLSProxyHandler(QuietHandler):
    upstream = ""
    protocol_version = "HTTP/1.1"
    capture_paths: tuple[str, ...] = ()
    capture_lock = threading.Lock()
    captures: list[dict[str, Any]] = []
    capture_sequence = 0

    @classmethod
    def _capture_matches(cls, request_path: str) -> bool:
        path = request_path.split("?", 1)[0]
        return any(
            path.startswith(pattern[:-1])
            if pattern.endswith("*")
            else path == pattern or path.endswith(pattern)
            for pattern in cls.capture_paths
        )

    def do_GET(self) -> None:  # noqa: N802
        self._proxy()

    def do_HEAD(self) -> None:  # noqa: N802
        self._proxy()

    def do_POST(self) -> None:  # noqa: N802
        self._proxy()

    def do_PUT(self) -> None:  # noqa: N802
        self._proxy()

    def do_DELETE(self) -> None:  # noqa: N802
        self._proxy()

    def _write_proxy_response_chunk(self, chunk: bytes, *, chunked: bool) -> None:
        if chunked:
            self.wfile.write(f"{len(chunk):X}\r\n".encode("ascii"))
            self.wfile.write(chunk)
            self.wfile.write(b"\r\n")
        else:
            self.wfile.write(chunk)
        self.wfile.flush()

    def _finish_proxy_response(self, *, chunked: bool) -> None:
        if chunked:
            self.wfile.write(b"0\r\n\r\n")
            self.wfile.flush()

    def _proxy(self) -> None:
        if self.path.split("?", 1)[0] == "/__fixture/proxy-evidence":
            if self.headers.get("x-fixture-control", "") != CONTROL_TOKEN:
                write_json(self, 403, {"error": "fixture control token required"})
                return
            with self.capture_lock:
                captures = json.loads(json.dumps(self.captures))
            write_json(self, 200, {"captures": captures})
            return
        size = int(self.headers.get("content-length", "0"))
        if size < 0 or size > 64 * 1024 * 1024:
            write_json(self, 413, {"error": "request is too large"})
            return
        parsed = urlsplit(self.upstream)
        if parsed.scheme != "http" or not parsed.hostname:
            write_json(self, 500, {"error": "TLS proxy upstream must be an internal HTTP origin"})
            return
        connection = http.client.HTTPConnection(parsed.hostname, parsed.port or 80, timeout=310)
        capture = self._capture_matches(self.path)
        request_hash = hashlib.sha256() if capture else None
        request_capture = bytearray()
        try:
            upstream_path = parsed.path.rstrip("/") + self.path
            connection.putrequest(self.command, upstream_path, skip_host=True, skip_accept_encoding=True)
            connection.putheader("Host", parsed.netloc)
            for key, value in self.headers.items():
                if key.lower() not in {"host", "connection", "content-length", "transfer-encoding"}:
                    connection.putheader(key, value)
            if size:
                connection.putheader("Content-Length", str(size))
            connection.endheaders()
            remaining = size
            while remaining:
                chunk = self.rfile.read(min(64 * 1024, remaining))
                if not chunk:
                    raise ConnectionError("client closed before request body completed")
                if request_hash is not None:
                    request_hash.update(chunk)
                    if len(request_capture) < 1024 * 1024:
                        request_capture.extend(chunk[: 1024 * 1024 - len(request_capture)])
                connection.send(chunk)
                remaining -= len(chunk)
            response = connection.getresponse()
        except Exception as exc:
            connection.close()
            write_json(self, 502, {"error": f"TLS proxy upstream failed: {exc}"})
            return
        try:
            self.send_response(response.status)
            content_length = response.getheader("content-length")
            response_has_body = self.command != "HEAD" and not (
                100 <= response.status < 200 or response.status in {204, 304}
            )
            downstream_chunked = response_has_body and content_length is None
            for key, value in response.headers.items():
                if key.lower() not in {"connection", "transfer-encoding", "content-length"}:
                    self.send_header(key, value)
            if content_length is not None:
                self.send_header("content-length", content_length)
            elif downstream_chunked:
                # http.client decodes an upstream chunked response. Re-encode
                # the decoded bytes for the downstream HTTP/1.1 connection so
                # a successful response ends with a protocol boundary instead
                # of relying on a TLS socket close.
                self.send_header("transfer-encoding", "chunked")
            self.end_headers()
            if response_has_body:
                try:
                    if capture:
                        response_hash = hashlib.sha256()
                        response_capture = bytearray()
                        response_size = 0
                        while True:
                            chunk = response.read(64 * 1024)
                            if not chunk:
                                break
                            response_hash.update(chunk)
                            response_size += len(chunk)
                            if len(response_capture) < 1024 * 1024:
                                response_capture.extend(
                                    chunk[: 1024 * 1024 - len(response_capture)]
                                )
                            self._write_proxy_response_chunk(chunk, chunked=downstream_chunked)
                        self._finish_proxy_response(chunked=downstream_chunked)
                        decoded_request: Any = None
                        if size and size <= 1024 * 1024:
                            try:
                                decoded_request = json.loads(bytes(request_capture))
                            except (UnicodeDecodeError, json.JSONDecodeError):
                                decoded_request = None
                        try:
                            decoded: Any = (
                                json.loads(bytes(response_capture))
                                if response_size <= 1024 * 1024
                                else {
                                    "non_json_sha256": "sha256:" + response_hash.hexdigest(),
                                    "size_bytes": response_size,
                                }
                            )
                        except (UnicodeDecodeError, json.JSONDecodeError):
                            decoded = {
                                "non_json_sha256": "sha256:" + response_hash.hexdigest(),
                                "size_bytes": response_size,
                            }
                        with self.capture_lock:
                            type(self).capture_sequence += 1
                            self.captures.append(
                                {
                                    "sequence": type(self).capture_sequence,
                                    "captured_at_unix_ms": int(time.time() * 1000),
                                    "method": self.command,
                                    "path": self.path,
                                    "status": response.status,
                                    "request_headers": {
                                        key: self.headers.get(key, "")
                                        for key in (
                                            "prefer",
                                            "content-type",
                                            "idempotency-key",
                                        )
                                        if self.headers.get(key) is not None
                                    },
                                    "request_size_bytes": size,
                                    "request_sha256": "sha256:" + request_hash.hexdigest()
                                    if request_hash is not None
                                    else "",
                                    "request_body": decoded_request,
                                    "body": decoded,
                                    "response_size_bytes": response_size,
                                    "response_sha256": "sha256:" + response_hash.hexdigest(),
                                }
                            )
                            # Bounded, but large enough to retain one complete
                            # claim/download/result exchange under heartbeat noise.
                            del self.captures[:-128]
                    else:
                        while True:
                            chunk = response.read(64 * 1024)
                            if not chunk:
                                break
                            self._write_proxy_response_chunk(chunk, chunked=downstream_chunked)
                        self._finish_proxy_response(chunked=downstream_chunked)
                except Exception:
                    # A chunked response without the terminating zero chunk is
                    # deliberately incomplete. Close this downstream connection
                    # so clients reject a truncated upstream body.
                    self.close_connection = True
                    raise
        finally:
            response.close()
            connection.close()


