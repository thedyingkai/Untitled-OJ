def managed_consumer_service(context_path: Path, port: int) -> None:
    """Long-lived generic consumer used by the strict Store/Agent gate.

    The process knows only the requirement name from its own Release.  It has
    no Gateway URL, provider address, token, deployment ID, or Orchestrator
    product hook; those are all read from the Agent materialized context.
    """

    def consume() -> None:
        while True:
            try:
                context, token, tls = load_context(context_path)
                value = http_json(binding_url(context, "echo"), token, tls)
                if value.get("value") != "cross-engine-binding-ok":
                    raise ValueError(f"unexpected provider response: {value!r}")
                permission = None
                if "permission_check" in context.get("bindings", {}):
                    permission = http_json(
                        binding_url(context, "permission_check"),
                        token,
                        tls,
                        method="POST",
                        value={
                            "user_id": 1,
                            "permission": "problem.view",
                            "scope_type": "global",
                            "scope_id": 0,
                        },
                    )
                    allowed = permission.get("data", permission).get("allowed")
                    if allowed is not True:
                        raise ValueError(
                            f"workload permission_check binding rejected known admin: {permission!r}"
                        )
                with ManagedConsumerState.lock:
                    ManagedConsumerState.result = {**value, "permission_check": permission}
                    ManagedConsumerState.error = ""
                    ManagedConsumerState.success_count += 1
                    ManagedConsumerState.context_generation = int(
                        context.get("generation", 0)
                    )
                print(
                    canonical_json({"status": "ok", "binding": "echo", "response": value}).decode(),
                    flush=True,
                )
                time.sleep(0.5)
            except Exception as exc:  # retry while the staged route becomes active
                with ManagedConsumerState.lock:
                    ManagedConsumerState.error = str(exc)[:512]
                time.sleep(0.25)

    threading.Thread(target=consume, name="managed-generic-consumer", daemon=True).start()
    ThreadingHTTPServer(("0.0.0.0", port), ManagedConsumerHandler).serve_forever()


