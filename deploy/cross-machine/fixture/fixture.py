def _base64url_unsigned(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).decode("ascii").rstrip("=")


def _generated_rsa_jwk(directory: Path) -> dict[str, str]:
    directory.mkdir(parents=True, exist_ok=True)
    key = directory / "oidc-rsa.pem"
    subprocess.run(
        ["openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", str(key)],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    modulus = subprocess.run(
        ["openssl", "rsa", "-in", str(key), "-noout", "-modulus"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    prefix = "Modulus="
    if not modulus.startswith(prefix):
        raise ValueError("openssl did not return an RSA modulus")
    number = int(modulus[len(prefix) :], 16)
    raw = number.to_bytes((number.bit_length() + 7) // 8, "big")
    return {
        "kty": "RSA",
        "kid": "cross-machine-oidc-1",
        "use": "sig",
        "alg": "RS256",
        "n": _base64url_unsigned(raw),
        "e": _base64url_unsigned((65537).to_bytes(3, "big")),
    }


