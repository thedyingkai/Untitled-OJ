def load_context(path: Path) -> tuple[dict[str, Any], str, ssl.SSLContext]:
    context = json.loads(path.read_text(encoding="utf-8"))
    token_path = Path(context["credential_file"])
    token = token_path.read_text(encoding="utf-8").strip()
    if not token or any(character.isspace() for character in token):
        raise ValueError("workload credential is invalid")
    if any(key in context for key in ("token", "admin_token", "management_token")):
        raise ValueError("service context embedded a credential")
    ca_file = context.get("gateway", {}).get("ca_file")
    tls = ssl.create_default_context(cafile=ca_file)
    return context, token, tls


def binding_url(context: dict[str, Any], name: str, relative: str = "") -> str:
    binding = context["bindings"][name]
    relative = "/" + relative.lstrip("/") if relative else ""
    return context["gateway"]["origin"].rstrip("/") + binding["base_path"].rstrip("/") + relative


def binding_head(
    context_path: Path,
    binding_name: str,
    relative_path: str,
    expected_deployment_id: str,
) -> dict[str, Any]:
    """Issue one bounded HEAD through an Agent-materialized ApiBinding.

    This probe is intentionally a workload, not a management client: its only
    inputs are the mounted Service Context, its sibling credential/CA files,
    the requirement name, and a provider-relative path.  The returned JSON is
    deliberately limited to non-secret response metadata.
    """

    parsed = urlsplit(relative_path)
    decoded_path = parsed.path
    for _ in range(2):
        decoded_path = unquote(decoded_path)
    if (
        not relative_path.startswith("/")
        or parsed.scheme
        or parsed.netloc
        or parsed.query
        or parsed.fragment
        or any(segment == ".." for segment in decoded_path.split("/"))
    ):
        raise ValueError("binding HEAD relative path is invalid")
    raw_context = json.loads(context_path.read_text(encoding="utf-8"))
    deployment = raw_context.get("deployment", {})
    gateway = raw_context.get("gateway", {})
    binding = raw_context.get("bindings", {}).get(binding_name)
    origin = str(gateway.get("origin", ""))
    parsed_origin = urlsplit(origin)
    generation = raw_context.get("generation")
    if (
        raw_context.get("schema_version") != 1
        or deployment.get("id") != expected_deployment_id
        or deployment.get("service") != "problem-service"
        or not str(deployment.get("node", "")).strip()
        or isinstance(generation, bool)
        or not isinstance(generation, int)
        or generation < 1
        or parsed_origin.scheme != "https"
        or not parsed_origin.hostname
        or parsed_origin.username is not None
        or parsed_origin.password is not None
        or parsed_origin.path not in ("", "/")
        or parsed_origin.query
        or parsed_origin.fragment
        or gateway.get("ca_file") != "/run/ojos/service/ca.pem"
        or raw_context.get("credential_file") != "/run/ojos/service/token"
    ):
        raise ValueError("binding HEAD requires the expected managed Problem Service Context")
    if (
        not isinstance(binding, dict)
        or not str(binding.get("binding_id", "")).strip()
        or binding.get("api_id") != "storage.object.head"
        or binding.get("base_path") != "/internal/apis/storage.object.head"
        or isinstance(binding.get("timeout_ms"), bool)
        or not isinstance(binding.get("timeout_ms"), int)
        or not 1 <= int(binding["timeout_ms"]) <= 300_000
    ):
        raise ValueError("binding HEAD requires a storage.object.head ApiBinding")
    context, token, tls = load_context(context_path)
    request = urllib.request.Request(
        binding_url(context, binding_name, relative_path),
        method="HEAD",
        headers={"authorization": "Bearer " + token},
    )

    def result(status: int, headers: Any) -> dict[str, Any]:
        raw_size = str(headers.get("Content-Length", "")).strip()
        try:
            size_bytes = int(raw_size) if raw_size else -1
        except ValueError:
            size_bytes = -1
        return {
            "status": int(status),
            "sha256_header": str(headers.get("X-OJOS-Object-Sha256", "")).strip(),
            "size_bytes": size_bytes,
            "storage_result_header": str(
                headers.get("X-OJOS-Storage-Result", "")
            ).strip(),
        }

    opener = urllib.request.build_opener(
        urllib.request.ProxyHandler({}),
        NoRedirectHandler(),
        urllib.request.HTTPSHandler(context=tls),
    )
    try:
        with opener.open(request, timeout=BINDING_HEAD_TIMEOUT_SECONDS) as response:
            return result(response.status, response.headers)
    except urllib.error.HTTPError as error:
        try:
            return result(error.code, error.headers)
        finally:
            error.close()


def http_json(
    url: str,
    token: str,
    tls: ssl.SSLContext,
    method: str = "GET",
    value: Any | None = None,
    headers: dict[str, str] | None = None,
) -> Any:
    body = canonical_json(value) if value is not None else None
    request_headers = {"authorization": "Bearer " + token}
    if body is not None:
        request_headers["content-type"] = "application/json"
    request_headers.update(headers or {})
    request = urllib.request.Request(url, data=body, method=method, headers=request_headers)
    with urllib.request.urlopen(request, context=tls, timeout=40) as response:
        return json.loads(response.read())


def verified_download(
    context: dict[str, Any], token: str, tls: ssl.SSLContext, reference: dict[str, Any]
) -> bytes:
    if reference.get("url"):
        raise ValueError("managed ApiResourceRef must not contain a URL")
    binding = str(reference["binding"])
    declared = context["bindings"][binding]
    if declared["api_id"] != reference["api_id"]:
        raise ValueError("ApiResourceRef does not match its named binding")
    relative = str(reference["relative_path"])
    if not relative.startswith("/") or "://" in relative or "/../" in relative:
        raise ValueError("ApiResourceRef relative path is invalid")
    request = urllib.request.Request(
        binding_url(context, binding, relative),
        method="GET",
        headers={"authorization": "Bearer " + token},
    )
    digest = hashlib.sha256()
    chunks: list[bytes] = []
    size = 0
    with urllib.request.urlopen(request, context=tls, timeout=40) as response:
        while True:
            chunk = response.read(16384)
            if not chunk:
                break
            size += len(chunk)
            if size > int(reference["size_bytes"]):
                raise ValueError("resource exceeded advertised size")
            digest.update(chunk)
            chunks.append(chunk)
    expected_digest = str(reference["sha256"]).removeprefix("sha256:")
    if size != int(reference["size_bytes"]) or digest.hexdigest() != expected_digest:
        raise ValueError("resource digest or size mismatch")
    return b"".join(chunks)


